/* Builds site/tools/joint-health-risk/jhra-01.js, the browser copy of the
   JHRA_01 engine, from app/src/engine (TypeScript -> plain JS, one file,
   no bundler). The public tool page scores on the device with exactly the
   engine the tests and the edge function use; tests/jhra-01-browser.test.ts
   fails if the committed file drifts. Run after any engine change:
     node scripts/build-jhra-browser.mjs */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const engine = path.resolve(here, '../src/engine');
export const OUTPUT = path.resolve(here, '../../site/tools/joint-health-risk/jhra-01.js');

function strip(file) {
  const src = readFileSync(path.join(engine, file), 'utf8');
  const js = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.ESNext, removeComments: false } }).outputText;
  return js
    .replace(/^import[\s\S]*?from\s+'[^']+';\s*$/gm, '')
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
    .replace(/^export\s+(const|function|let)\s/gm, '$1 ')
    .replace(/^\/\/# sourceMappingURL.*$/gm, '')
    .trim();
}

export function browserBundle() {
  return [
    '/* GENERATED by app/scripts/build-jhra-browser.mjs from app/src/engine/jhra-01-definition.ts',
    '   and app/src/engine/jhra-01.ts. Do not edit by hand. Exposes window.JHRA. */',
    '(function () {',
    "'use strict';",
    strip('jhra-01-definition.ts'),
    strip('jhra-01.ts'),
    'window.JHRA = { scoreJHRA, jhraFingerprint, chairStandRange, injuryPoints, contextPoints,',
    '  JHRA_CODE, JHRA_VERSION_LABEL, JHRA_ALGORITHM_VERSION, JHRA_SAFETY, JHRA_QUESTIONS, JHRA_DOMAINS,',
    '  JHRA_DOMAIN_ORDER, JHRA_TIERS, JHRA_INJURY_TYPES, JHRA_INJURY_JOINTS, JHRA_INJURY_SIDES,',
    '  JHRA_INJURY_TREATMENTS, JHRA_MAX_INJURIES, JHRA_FLAG_COPY, JHRA_SAFETY_COPY, JHRA_REASSESS_DAYS };',
    '})();',
    ''
  ].join('\n');
}

if (process.argv[1] && process.argv[1].endsWith('build-jhra-browser.mjs')) {
  writeFileSync(OUTPUT, browserBundle());
  console.log('wrote', OUTPUT);
}
