/* Writes supabase/migrations/20261125181000_jhra_01_publish.sql from the
   engine's own definition (scripts/export-jhra-definition.mjs). Re-running it
   reproduces the committed file; tests/jhra-01-publish.test.ts checks that
   the embedded JSON equals the current export. Never edit the SQL by hand: a
   published version is immutable, so a change is a new version. */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { definition } from './export-jhra-definition.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const MIGRATION = path.resolve(here, '../../supabase/migrations/20261125181000_jhra_01_publish.sql');
const TAG = '$def$';

export function migrationSql() {
  const json = JSON.stringify(definition);
  if (json.includes(TAG)) throw new Error('definition contains the dollar-quote tag');
  return [
    `-- JHRA_01 · Joint health risk assessment, version ${definition.version_label}`,
    `-- (${definition.algorithm_version}). GENERATED by app/scripts/write-jhra-publish-migration.mjs`,
    '-- from app/src/engine/jhra-01-definition.ts. Do not edit by hand.',
    '--',
    "-- Free (access_key 'free'), Exercise & Mobility > Joint Health (P1-C1).",
    '-- The public tool page scores on the device without sign-in; saving a',
    '-- result to an account uses this version. Requires',
    '-- 20261125180000_jhra_tier_system.sql (tier system jhra_risk).',
    '',
    'insert into public.assessments (code, title, short_title, description, instrument_kind, audience,',
    '                                tier_system, pillar_id, category_id, access_key, est_minutes, version, status, safety_note)',
    `values ('${definition.code}', 'Joint health risk assessment', 'Joint health risk',`,
    "        'A seven-part check of past injuries, metabolic health, muscle, function, weight change, medications and current joint symptoms. Produces a 0-100 Joint Risk Score (higher is more risk), an action tier, priority areas and flags.',",
    "        'questionnaire', 'user', 'jhra_risk', 1, 1, 'free', 12, 1, 'published',",
    "        'Educational self-assessment, not a diagnosis. Any safety yes stops before scoring. Never start, stop or change a medication based on the result.')",
    'on conflict (code) do nothing;',
    '',
    'insert into public.assessment_versions (assessment_id, version_label, algorithm_version, status, definition, approval_note, published_at)',
    `select a.id, '${definition.version_label}', '${definition.algorithm_version}', 'published', ${TAG}${json}${TAG}::jsonb,`,
    "       'JHRA v1.0 draft (Randy Bauer, PT). Pilot weighting, pending clinical sign-off and counsel-approved privacy copy before release.',",
    '       now()',
    `from public.assessments a where a.code = '${definition.code}'`,
    'on conflict (assessment_id, version_label) do nothing;',
    ''
  ].join('\n');
}

if (process.argv[1] && process.argv[1].endsWith('write-jhra-publish-migration.mjs')) {
  const sql = migrationSql();
  writeFileSync(MIGRATION, sql);
  console.log('wrote', MIGRATION, sql.length, 'bytes');
}
