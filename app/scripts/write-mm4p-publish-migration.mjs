/* Writes supabase/migrations/20261111181000_mm_4p_01_publish.sql from the
   engine's own definition (scripts/export-mm4p-definition.mjs). Re-running it
   reproduces the committed file; tests/mm-4p-01-publish.test.ts checks that
   the embedded JSON equals the current export. Never edit the SQL by hand: a
   published version is immutable, so a change is a new version. */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { definition } from './export-mm4p-definition.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const MIGRATION = path.resolve(here, '../../supabase/migrations/20261111181000_mm_4p_01_publish.sql');
const TAG = '$def$';

export function migrationSql() {
  const json = JSON.stringify(definition);
  if (json.includes(TAG)) throw new Error('definition contains the dollar-quote tag');
  return [
    `-- MM_4P_01 · Muscle-Meta Matrix™ full assessment, version ${definition.version_label}`,
    `-- (${definition.algorithm_version}). GENERATED by app/scripts/write-mm4p-publish-migration.mjs`,
    '-- from app/src/engine/mm-4p-01-definition.ts. Do not edit by hand.',
    '--',
    "-- Free (access_key 'free'): all 4 pillars and 12 categories scored and shown",
    '-- (spec D-3, C-8). Sign-in required to start: assessment versions are',
    '-- readable by signed-in members only (Randy, 2026-11-09). The safety',
    '-- question is the first screen and routes only.',
    '',
    'insert into public.assessments (code, legacy_code, title, short_title, description, instrument_kind, audience,',
    '                                tier_system, access_key, est_minutes, version, status, safety_note)',
    `values ('${definition.code}', '${definition.legacy_code}', 'Muscle-Meta Matrix™ full assessment', 'Full assessment',`,
    "        'Forty-two scored questions across all 4 pillars and 12 categories, plus profile and preference questions. Produces the 0-100 MM™ Health Score, pillar and category scores, flags and a starting level.',",
    "        'questionnaire', 'user', 'mm_health_score', 'free', 15, 1, 'published',",
    "        'Educational self-assessment, not a diagnosis. The safety answer changes the route, never a score.')",
    'on conflict (code) do nothing;',
    '',
    'insert into public.assessment_versions (assessment_id, version_label, algorithm_version, status, definition, approval_note, published_at)',
    `select a.id, '${definition.version_label}', '${definition.algorithm_version}', 'published', ${TAG}${json}${TAG}::jsonb,`,
    "       'Spec v1 approved 2026-10-08; FI3/BA2 scores and flag wording approved 2026-11-11; starting-level rule is a pilot rule (2026-11-11).',",
    '       now()',
    `from public.assessments a where a.code = '${definition.code}'`,
    'on conflict (assessment_id, version_label) do nothing;',
    ''
  ].join('\n');
}

if (process.argv[1] && process.argv[1].endsWith('write-mm4p-publish-migration.mjs')) {
  const sql = migrationSql();
  writeFileSync(MIGRATION, sql);
  console.log('wrote', MIGRATION, sql.length, 'bytes');
}
